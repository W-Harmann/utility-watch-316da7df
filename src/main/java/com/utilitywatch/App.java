/**
 * A second entry point that only passes control to {@link Main#main(String[])}.
 */
public class App {
    /**
     * Starts the application by calling {@link Main#main(String[])}.
     *
     * @param args the command-line arguments, passed on unchanged
     */
    public static void main(String[] args) {
        Main.main(args);
    }
}
